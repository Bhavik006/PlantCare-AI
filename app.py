import streamlit as st
from google import genai
from prompts import (
    SYSTEM_PROMPT,
    WELCOME_MESSAGE_TEMPLATE,
    SUMMARY_REQUEST_PROMPT
)
from google.genai import types
import smtplib
from email.message import EmailMessage


MODEL_NAME = "gemini-3.5-flash"


st.set_page_config(
    page_title="PlantCare AI",
    page_icon="🌱",
    layout="centered"
)
st.markdown(
    """
    <style>
    .main-title {
        text-align: center;
        font-size: 2.5rem;
        font-weight: 700;
        margin-bottom: 0.2rem;
    }

    .subtitle {
        text-align: center;
        color: #6b7280;
        margin-bottom: 2rem;
    }
    </style>
    """,
    unsafe_allow_html=True
)


GEMINI_API_KEY = st.secrets["GEMINI_API_KEY"]


@st.cache_resource
def get_gemini_client():
    return genai.Client(api_key=GEMINI_API_KEY)


gemini_client = get_gemini_client()
def send_email(report, recipient):
    message = EmailMessage()

    message["Subject"] = "🌿 Your PlantCare AI Report"
    message["From"] = st.secrets["EMAIL_ADDRESS"]
    message["To"] = recipient

    message.set_content(
        f"""Hello {st.session_state.name},

Here is your PlantCare AI report:

{report}

---
Generated by PlantCare AI 🌱
"""
    )

    with smtplib.SMTP_SSL("smtp.gmail.com", 465) as server:
        server.login(
            st.secrets["EMAIL_ADDRESS"],
            st.secrets["EMAIL_APP_PASSWORD"]
        )
        server.send_message(message)
if "onboarded" not in st.session_state:
    st.markdown(
            '<div class="main-title">🌱 PlantCare AI</div>',
            unsafe_allow_html=True
                )

    st.markdown(
                '<div class="subtitle">Understand your plant. Care for it better.</div>',
                unsafe_allow_html=True
            )

    with st.form("onboarding_form"):
        name = st.text_input("Your name")

        email = st.text_input(
            "Email address",
            placeholder="you@example.com"
        )

        submitted = st.form_submit_button("Start PlantCare AI 🌿")

    if submitted:
        if not name.strip() or not email.strip():
            st.warning("Please enter both your name and email address.")
        else:
            st.session_state.name = name.strip()
            st.session_state.email = email.strip()

            st.session_state.chat = gemini_client.chats.create(
                 model=MODEL_NAME,
                config=types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT
                    )
                    )

            st.session_state.messages = []
            st.session_state.onboarded = True

            st.rerun()

    st.stop()
    # Chat interface

st.title("🌱 PlantCare AI")

if not st.session_state.messages:
    st.session_state.messages.append({
        "role": "assistant",
        "kind": "text",
        "content": WELCOME_MESSAGE_TEMPLATE.format(
            name=st.session_state.name
        )
    })

for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        if message["kind"] == "text":
            st.write(message["content"])
        elif message["kind"] == "image":
            st.image(message["content"])
# Chat input
prompt = st.chat_input(
    "Ask about your plant...",
    accept_file=True,
    file_type=["jpg", "jpeg", "png"]
)

if prompt:
    user_text = prompt.text
    uploaded_file = prompt.files[0] if prompt.files else None

    # Show user's message
    if user_text:
        st.session_state.messages.append({
            "role": "user",
            "kind": "text",
            "content": user_text
        })

    # Show uploaded image
    if uploaded_file:
        photo_bytes = uploaded_file.getvalue()

        st.session_state.messages.append({
            "role": "user",
            "kind": "image",
            "content": photo_bytes
        })

    # Send to Gemini
    if uploaded_file:
        photo_bytes = uploaded_file.getvalue()

        response = st.session_state.chat.send_message([
            types.Part.from_bytes(
                data=photo_bytes,
                mime_type=uploaded_file.type
            ),
            user_text if user_text else "Analyze this plant photo."
        ])
    else:
        response = st.session_state.chat.send_message(user_text)

    # Store AI response
    st.session_state.messages.append({
        "role": "assistant",
        "kind": "text",
        "content": response.text
    })

    st.rerun()
    st.divider()

if st.button("📋 Generate Plant Care Report"):
    with st.spinner("Preparing your plant care report..."):
        report_response = st.session_state.chat.send_message(
            SUMMARY_REQUEST_PROMPT
        )

        st.session_state.report = report_response.text

if "report" in st.session_state:
    st.subheader("🌿 Plant Care Report")
    st.markdown(st.session_state.report)

    if st.button("📧 Send Report to My Email"):
        try:
            send_email(
                st.session_state.report,
                st.session_state.email
            )

            st.success(
                f"Report sent successfully to {st.session_state.email}!"
            )

        except Exception as e:
            st.error(f"Could not send email: {e}")